package com.readerscircle.discussions.dto;

import java.util.List;

/** Discussion card + detail shape consumed by the discussions UI. */
public record DiscussionDto(
    String id,
    String bookTitle,
    String author,
    String genre,
    Integer pageCount,
    Integer publicationYear,
    String coverImageUrl,
    String keyQuote,
    String quoteAuthor,
    String discussionTitle,
    String discussionExcerpt,
    String tag,
    List<String> tags,
    String tagColor,
    int repliesCount,
    int viewsCount,
    String timeAgo,
    String createdAt,
    String createdBy,
    String createdById,
    int membersCount,
    List<String> participantAvatars,
    List<ThreadDto> threads,
    String circleId,
    String circleName,
    int likesCount,
    boolean userLiked) {

  public DiscussionDto(
      String id,
      String bookTitle,
      String author,
      String genre,
      Integer pageCount,
      Integer publicationYear,
      String coverImageUrl,
      String keyQuote,
      String quoteAuthor,
      String discussionTitle,
      String discussionExcerpt,
      String tag,
      String tagColor,
      int repliesCount,
      int viewsCount,
      String timeAgo,
      String createdAt,
      String createdBy,
      String createdById,
      int membersCount,
      List<String> participantAvatars,
      List<ThreadDto> threads) {
    this(
        id,
        bookTitle,
        author,
        genre,
        pageCount,
        publicationYear,
        coverImageUrl,
        keyQuote,
        quoteAuthor,
        discussionTitle,
        discussionExcerpt,
        tag,
        tag == null || tag.isBlank() ? List.of() : List.of(tag),
        tagColor,
        repliesCount,
        viewsCount,
        timeAgo,
        createdAt,
        createdBy,
        createdById,
        membersCount,
        participantAvatars,
        threads,
        null,
        null,
        0,
        false);
  }
}
